def _format_contexts(contexts: List[str], max_chars_each: int = 400) -> str:
    if not contexts:
        return ""
    blocks = []
    for i, ctx in enumerate(contexts, 1):
        text = (ctx or "").strip()
        if not text:
            continue
        if len(text) > max_chars_each:
            text = text[:max_chars_each] + "…"
        blocks.append(f"[资料{i}] {text}")
    if not blocks:
        return ""
    header = (
        "以下是从知识库检索到的相关历史文献片段，请优先依据资料作答：\n"
    )
    return header + "\n".join(blocks) + "\n\n"


def build_user_message(
    section: str,
    question: str,
    contexts: Optional[List[str]] = None,
) -> str:
    """构造 user message。

    Visual-First 强制约束（T3）：
      - 简答题尾部显式加 '不要 "基于以上资料…"' 等啰嗦前缀拦截
      - VQA 路径走 build_short_vqa_user / build_choice_vqa_user，本函数主要兜底
    """
    contexts = contexts or []
    ctx_block = _format_contexts(contexts)
    is_vqa = "VQA" in section

    if "选择" in section:
        if is_vqa:
            tail = (
                "请先观察图像穷举各选项对应的视觉细节，再结合资料判断，"
                "直接输出选项字母（单选 1 个或多选连写多个，无分隔符，无任何前缀）："
            )
        else:
            tail = "请直接输出选项字母（单选 1 个或多选连写多个，无分隔符）："
    elif "判断" in section:
        if is_vqa:
            tail = "请优先观察图像，再结合资料，直接输出 '正确' 或 '错误'（无任何前缀）："
        else:
            tail = "请直接输出 '正确' 或 '错误'："
    else:
        # 简答题：硬截断"基于以上资料""根据图片"等啰嗦前缀
        if is_vqa:
            tail = (
                "请优先从图中直接观察，输出最简短答案（≤8 字、无前缀、无标点）。"
                "禁止 '基于以上资料' / '根据图片' / '答案是' 等开场白："
            )
        else:
            tail = (
                "请直接输出最简短答案（≤8 字、无前缀、无标点）。"
                "禁止 '基于以上资料' / '答案是' / '为' 等开场白："
            )

    return f"{ctx_block}[题目] {question.strip()}\n\n{tail}"


