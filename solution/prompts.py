# 选择题 few-shot: 单选 + 多选 (用直答格式即可, 模型会自适应是否 CoT)
FEWSHOT_CHOICE = [
    ("以下哪种颜色由红色和黄色混合而成？A. 紫色 B. 橙色 C. 绿色 D. 棕色", "B"),
    ("以下哪些是哺乳动物？A. 鲸鱼 B. 鳄鱼 C. 蝙蝠 D. 海豚", "ACD"),
]

FEWSHOT_JUDGE = [
    ("水在标准大气压下沸点为 100 摄氏度。", "正确"),
    ("太阳从西边升起。", "错误"),
]

FEWSHOT_SHORT = [
    ("一年有多少个月？", "12"),
    ("地球的天然卫星叫什么？", "月球"),
]


def fewshot_block(section: str) -> str:
    if "选择" in section:
        pairs = FEWSHOT_CHOICE
        tail = "请直接输出选项字母："
    elif "判断" in section:
        pairs = FEWSHOT_JUDGE
        tail = "请直接输出 '正确' 或 '错误'："
    else:
        pairs = FEWSHOT_SHORT
        tail = "请直接输出最简短答案："
    lines = ["以下是输出格式演示（仅供格式参考，与本题无关）："]
    for q, a in pairs:
        lines.append(f"  题目：{q}\n  {tail}{a}")
    return "\n".join(lines) + "\n\n"


