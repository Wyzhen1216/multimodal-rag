def fallback_answer(section: str) -> str:
    if "选择" in section:
        return "A"
    if "判断" in section:
        return "正确"
    return "无"


def _format_contexts_soft(contexts: List[str], max_chars_each: int = 400) -> str:
    """软化版 ctx 格式化：措辞改为'参考资料'，明确说明以模型知识为主。"""
    if not contexts:
        return ""
    blocks = []
    for i, ctx in enumerate(contexts, 1):
        text = (ctx or "").strip()
        if not text:
            continue
        if len(text) > max_chars_each:
            text = text[:max_chars_each] + "…"
        blocks.append(f"[参考{i}] {text}")
    if not blocks:
        return ""
    header = (
        "以下是检索到的参考资料（仅供辅助参考，请以你的历史知识为主要判断依据）：\n"
    )
    return header + "\n".join(blocks) + "\n\n"


def build_judge_user_soft(
    section: str,
    question: str,
    contexts: Optional[List[str]] = None,
) -> str:
    """判断题软化 RAG 版 user message。

    无 ctx 时不注入资料块；有 ctx 时使用弱化措辞，不给模型"资料优先"的暗示。
    """
    contexts = contexts or []
    ctx_block = _format_contexts_soft(contexts)
    tail = "请根据你的历史知识直接输出 '正确' 或 '错误'："
    return f"{ctx_block}[题目] {question.strip()}\n\n{tail}"


def build_short_vqa_user(
    question: str,
    contexts: Optional[List[str]] = None,
) -> str:
    """简答VQA user message：图像优先，RAG 仅辅助。

    有 ctx 时用弱化措辞，明确以图像观察为主，资料仅供背景参考。
    """
    contexts = contexts or []
    ctx_block = ""
    if contexts:
        blocks = []
        for i, ctx in enumerate(contexts[:3], 1):  # 最多3条，不干扰视觉判断
            text = (ctx or "").strip()
            if not text:
                continue
            if len(text) > 200:
                text = text[:200] + "…"
            blocks.append(f"[背景参考{i}] {text}")
        if blocks:
            ctx_block = (
                "以下是辅助背景资料（仅供参考，答案应优先从图中直接观察）：\n"
                + "\n".join(blocks)
                + "\n\n"
            )
    tail = (
        "请优先根据图像直接观察，再参考背景资料（如有），"
        "输出最简短答案（≤8字、无前缀、无标点）。"
        "禁止 '基于以上资料' / '根据图片' / '答案是' / '为' 等开场白："
    )
    return f"{ctx_block}[题目] {question.strip()}\n\n{tail}"


def build_extract_user_message(
    question: str,
    contexts: Optional[List[str]] = None,
) -> str:
    """简答QA 提取模式 user message：强调从资料原文中定位答案，而非凭空生成。"""
    contexts = contexts or []
    ctx_block = _format_contexts(contexts)
    tail = (
        "请从以上资料中定位并提取对该问题的准确原文术语（不要改写，不要截断）："
    )
    return f"{ctx_block}[题目] {question.strip()}\n\n{tail}"
