# ============================================================================
# DMQR-RAG (Diverse Multi-Query Rewrite) —— 双阶段图文对齐检索
#
# 设计思想 (基于 DMQR-RAG 沿沿研究)：
#   - Phase A: 视觉特征抽取  (SYS_IMAGE_DESC)
#               用 LLM 对图像产出 ≤50 字关键特征描述
#               覆盖：器物类型 / 纹饰 / 铭文 / 形象 / 颜色 / 结构
#   - Phase B: 视觉 + 题干 → 陈述式检索 query  (SYS_IMAGE_AS_QUERY)
#               将 Phase A 的特征与题干语义融合成可直接送向量库的陈述句
#               用于解决 underspecified 查询问题
#
# 两阶段串接由 main.dmqr_build_image_query() 编排。
# ============================================================================

# ---------- 图像描述（DMQR Phase A：视觉特征抽取） ----------
