def fewshot_block(section: str) -> str:
    if "选择" in section:
        pairs = FEWSHOT_CHOICE
        tail = "请直接输出选项字母："
    elif "判断" in section:
        pairs = FEWSHOT_JUDGE
        tail = "请直接输出 '正确' 或 '错误'："
    else:
        pairs = FEWSHOT_SHORT
        tail = "请直接输出最简短答案："
    lines = ["以下是输出格式演示（仅供格式参考，与本题无关）："]
    for q, a in pairs:
        lines.append(f"  题目：{q}\n  {tail}{a}")
    return "\n".join(lines) + "\n\n"


